// Repo is the ops-scripts checkout this binary drives. The bash scripts stay
// the source of truth; this program only presents them and runs them.
type Repo struct {
	Root   string
	Config string // optional client config passed with -c
}

type Module struct {
	File, Name, Desc string
}

func findRoot(flagRoot string) (string, error) {
	var candidates []string
	if flagRoot != "" {
		candidates = []string{flagRoot}
	} else {
		if exe, err := os.Executable(); err == nil {
			if exe, err = filepath.EvalSymlinks(exe); err == nil {
				d := filepath.Dir(exe)
				candidates = append(candidates, d, filepath.Dir(d))
			}
		}
		if wd, err := os.Getwd(); err == nil {
			candidates = append(candidates, wd)
		}
		candidates = append(candidates, "/opt/ops-scripts")
	}
	for _, c := range candidates {
		if fileExists(filepath.Join(c, "bootstrap.sh")) && fileExists(filepath.Join(c, "modules")) {
			return filepath.Abs(c)
		}
	}
	return "", errors.New("could not find the ops-scripts folder (bootstrap.sh); pass --root")
}

func fileExists(p string) bool { _, err := os.Stat(p); return err == nil }

func (r *Repo) path(parts ...string) string {
	return filepath.Join(append([]string{r.Root}, parts...)...)
}

// Modules lists modules/*.sh in run order. The description is the module's
// second line (its one-line summary comment).
func (r *Repo) Modules() ([]Module, error) {
	files, err := filepath.Glob(r.path("modules", "*.sh"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	var mods []Module
	for _, f := range files {
		base := strings.TrimSuffix(filepath.Base(f), ".sh")
		name := base
		if i := strings.Index(base, "-"); i >= 0 {
			name = base[i+1:]
		}
		mods = append(mods, Module{File: f, Name: name, Desc: secondLineComment(f)})
	}
	return mods, nil
}

func secondLineComment(file string) string {
	fh, err := os.Open(file)
	if err != nil {
		return ""
	}
	defer fh.Close()
	sc := bufio.NewScanner(fh)
	for i := 0; sc.Scan(); i++ {
		if i == 1 {
			return strings.TrimSpace(strings.TrimPrefix(sc.Text(), "#"))
		}
	}
	return ""
}

func enableVar(module string) string {
	return "ENABLE_" + strings.ToUpper(strings.ReplaceAll(module, "-", "_"))
}

// LoadConfig evaluates config/default.env (+ the -c file) with bash, exactly
// like the scripts do, and returns the resulting variables.
func (r *Repo) LoadConfig() (map[string]string, error) {
	script := `set -a; . "$1/config/default.env"; if [ -n "$2" ]; then . "$2"; fi; env -0`
	out, err := exec.Command("bash", "-c", script, "_", r.Root, r.Config).Output()
	if err != nil {
		return nil, fmt.Errorf("loading config: %w", err)
	}
	cfg := map[string]string{}
	for _, kv := range strings.Split(string(out), "\x00") {
		if k, v, ok := strings.Cut(kv, "="); ok {
			cfg[k] = v
		}
	}
	return cfg, nil
}

// Env is the environment for running scripts: ours plus OPS_CONFIG if set.
func (r *Repo) Env() []string {
	env := os.Environ()
	if r.Config != "" {
		env = append(env, "OPS_CONFIG="+r.Config)
	}
	return env
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// WriteChoices writes a config file bootstrap.sh can use (-c). With forSave,
// secrets are left out (as a comment, so a value passed via env still works).
func (r *Repo) WriteChoices(path string, vals map[string]string, keys []string, forSave bool) error {
	var b strings.Builder
	host, _ := os.Hostname()
	fmt.Fprintf(&b, "# Generated by ops on %s on %s\n", time.Now().Format(time.RFC3339), host)
	if r.Config != "" {
		if base, err := os.ReadFile(r.Config); err == nil {
			fmt.Fprintf(&b, "# Based on %s\n%s\n\n# --- Choices made in ops (these win) ---\n", r.Config, base)
		}
	}
	for _, k := range keys {
		if forSave && isSecret(k) {
			fmt.Fprintf(&b, "# %s is a secret and not saved. Pass it when you run: sudo %s=... ./bootstrap.sh -c <this file>\n", k, k)
			continue
		}
		fmt.Fprintf(&b, "%s=%s\n", k, shellQuote(vals[k]))
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0o600)
}

type hostInfo struct {
	Name, OS, IP, Arch string
}

func readHostInfo() hostInfo {
	h := hostInfo{Arch: runtime.GOARCH}
	h.Name, _ = os.Hostname()
	if data, err := os.ReadFile("/etc/os-release"); err == nil {
		for _, line := range strings.Split(string(data), "\n") {
			if v, ok := strings.CutPrefix(line, "PRETTY_NAME="); ok {
				h.OS = strings.Trim(v, `"`)
			}
		}
	}
	if ifaces, err := net.Interfaces(); err == nil {
		for _, ifc := range ifaces {
			if ifc.Flags&net.FlagUp == 0 || ifc.Flags&net.FlagLoopback != 0 ||
				strings.HasPrefix(ifc.Name, "docker") || strings.HasPrefix(ifc.Name, "br-") ||
				strings.HasPrefix(ifc.Name, "veth") || strings.HasPrefix(ifc.Name, "tailscale") {
				continue
			}
			addrs, _ := ifc.Addrs()
			for _, a := range addrs {
				if ipn, ok := a.(*net.IPNet); ok && ipn.IP.To4() != nil {
					h.IP = ipn.IP.String()
					return h
				}
			}
		}
	}
	return h
}
